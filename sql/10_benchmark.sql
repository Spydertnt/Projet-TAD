BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE benchmark_results PURGE';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -942 THEN
        RAISE;
    END IF;
END;
/

CREATE TABLE benchmark_results (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_id        VARCHAR2(20) NOT NULL,
    query_desc      VARCHAR2(500) NOT NULL,
    scenario        VARCHAR2(30) NOT NULL,
    execution_ms    NUMBER,
    rows_returned   NUMBER,
    run_date        TIMESTAMP DEFAULT SYSTIMESTAMP
) TABLESPACE TS_MATERIEL;

CREATE OR REPLACE PROCEDURE SP_BENCHMARK_QUERY (
    p_query_id IN VARCHAR2,
    p_query_desc IN VARCHAR2,
    p_scenario IN VARCHAR2,
    p_sql IN CLOB
)
AS
    v_start NUMBER;
    v_end NUMBER;
    v_count NUMBER;
BEGIN
    v_start := DBMS_UTILITY.GET_TIME;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM (' || p_sql || ')' INTO v_count;
    v_end := DBMS_UTILITY.GET_TIME;

    INSERT INTO benchmark_results (query_id, query_desc, scenario, execution_ms, rows_returned)
    VALUES (p_query_id, p_query_desc, p_scenario, (v_end - v_start) * 10, v_count);
    COMMIT;
END SP_BENCHMARK_QUERY;
/

CREATE OR REPLACE PROCEDURE SP_RUN_BENCHMARK_ASSETS (
    p_scenario IN VARCHAR2 DEFAULT 'AVEC_INDEX'
)
AS
BEGIN
    SP_BENCHMARK_QUERY(
        'Q1',
        'Recherche materiel par nom',
        p_scenario,
        'SELECT a.id FROM assets a WHERE UPPER(a.name) LIKE ''PC-CERGY%'''
    );

    SP_BENCHMARK_QUERY(
        'Q2',
        'Inventaire par site et categorie',
        p_scenario,
        'SELECT e.site_code, a.asset_type, COUNT(*) nb
        FROM assets a JOIN sites e ON a.site_id = e.id
        GROUP BY e.site_code, a.asset_type'
    );

    SP_BENCHMARK_QUERY(
        'Q3',
        'Tickets ouverts par priorite',
        p_scenario,
        'SELECT t.status, t.priority, COUNT(*) nb
        FROM tickets t
        WHERE t.status IN (''NOUVEAU'', ''ASSIGNE'', ''EN_COURS'')
        GROUP BY t.status, t.priority'
    );

    SP_BENCHMARK_QUERY(
        'Q4',
        'Recherche materiel par numero de serie',
        p_scenario,
        'SELECT a.id FROM assets a WHERE UPPER(a.serial_number) = ''SN-2026-CERGY-00001'''
    );

    SP_BENCHMARK_QUERY(
        'Q5',
        'Reseau des appareils',
        p_scenario,
        'SELECT a.name, np.port_name, ipn.network_name, ipn.vlan_tag, ia.ip_address
        FROM assets a
            JOIN network_ports np ON np.asset_id = a.id
            LEFT JOIN ip_addresses ia ON ia.network_port_id = np.id
            LEFT JOIN ip_networks ipn ON ia.ip_network_id = ipn.id'
    );

    SP_BENCHMARK_QUERY(
        'Q6',
        'Utilisateurs avec profils',
        p_scenario,
        'SELECT u.login, p.name
        FROM users u
            JOIN profiles_users pu ON pu.user_id = u.id
            JOIN profiles p ON p.id = pu.profile_id'
    );
END SP_RUN_BENCHMARK_ASSETS;
/
