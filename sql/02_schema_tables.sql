) TABLESPACE TS_SUPPORT;

-- Supprimer les tickets liés à un PC supprimé
ALTER TABLE tickets DROP CONSTRAINT fk_ticket_comp;
ALTER TABLE tickets ADD CONSTRAINT fk_ticket_comp 
FOREIGN KEY (computers_id) REFERENCES computers(id) ON DELETE CASCADE;

CREATE TABLE tickets (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entities_id     NUMBER NOT NULL,
    title           VARCHAR2(255) NOT NULL,
    description     CLOB NOT NULL,
    status          VARCHAR2(30) DEFAULT 'NOUVEAU' NOT NULL
        CHECK (status IN ('NOUVEAU','ASSIGNE','EN_COURS','EN_ATTENTE','RESOLU','CLOS','ANNULE')),
    priority        VARCHAR2(20) DEFAULT 'MOYENNE' NOT NULL
        CHECK (priority IN ('BASSE','MOYENNE','HAUTE','CRITIQUE')),
    urgency         VARCHAR2(20) DEFAULT 'MOYENNE' NOT NULL
        CHECK (urgency IN ('BASSE','MOYENNE','HAUTE','CRITIQUE')),
    impact          VARCHAR2(20) DEFAULT 'MOYEN' NOT NULL
        CHECK (impact IN ('FAIBLE','MOYEN','ELEVE','MAJEUR')),
    requester_users_id NUMBER NOT NULL,
    assigned_groups_id NUMBER,
    ticket_categories_id NUMBER,
    computers_id    NUMBER,
    monitors_id     NUMBER,
    peripherals_id  NUMBER,
    printers_id     NUMBER,
    phones_id       NUMBER,
    network_equipments_id NUMBER,
    resolution      CLOB,
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_assigned   TIMESTAMP,
    date_resolved   TIMESTAMP,
    date_closed     TIMESTAMP,
    CONSTRAINT fk_ticket_entity FOREIGN KEY (entities_id) REFERENCES entities(id),
    CONSTRAINT fk_ticket_requester FOREIGN KEY (requester_users_id) REFERENCES users(id),
    CONSTRAINT fk_ticket_assigned_group FOREIGN KEY (assigned_groups_id) REFERENCES groups(id),
    CONSTRAINT fk_ticket_category FOREIGN KEY (ticket_categories_id) REFERENCES ticket_categories(id),
    CONSTRAINT fk_ticket_comp FOREIGN KEY (computers_id) REFERENCES computers(id),
    CONSTRAINT fk_ticket_mon FOREIGN KEY (monitors_id) REFERENCES monitors(id),
    CONSTRAINT fk_ticket_per FOREIGN KEY (peripherals_id) REFERENCES peripherals(id),
    CONSTRAINT fk_ticket_pri FOREIGN KEY (printers_id) REFERENCES printers(id),
    CONSTRAINT fk_ticket_pho FOREIGN KEY (phones_id) REFERENCES phones(id),
    CONSTRAINT fk_ticket_neq FOREIGN KEY (network_equipments_id) REFERENCES network_equipments(id),
    CONSTRAINT chk_ticket_one_asset CHECK (
        (CASE WHEN computers_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN monitors_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN peripherals_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN printers_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN phones_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN network_equipments_id IS NOT NULL THEN 1 ELSE 0 END) = 1
    )
) TABLESPACE TS_SUPPORT;

CREATE TABLE ticket_users (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tickets_id      NUMBER NOT NULL,
    users_id        NUMBER NOT NULL,
    role            VARCHAR2(30) DEFAULT 'TECHNICIEN' NOT NULL
