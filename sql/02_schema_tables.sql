CREATE TABLE ticket_categories (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(255) NOT NULL UNIQUE,
    description     VARCHAR2(1000),
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
