CREATE TABLE entities (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(255) NOT NULL,
    entities_id     NUMBER,
    hier_level      NUMBER DEFAULT 1 NOT NULL,
    completename    VARCHAR2(1000),
    address         VARCHAR2(500),
    postcode        VARCHAR2(20),
    town            VARCHAR2(255),
    country         VARCHAR2(255),
    site_code       VARCHAR2(10) CHECK (site_code IN ('CERGY','PAU')),
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP
) TABLESPACE TS_MATERIEL;

ALTER TABLE entities ADD CONSTRAINT fk_entities_parent
    FOREIGN KEY (entities_id) REFERENCES entities(id);

CREATE TABLE locations (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entities_id     NUMBER NOT NULL,
    name            VARCHAR2(255) NOT NULL,
    locations_id    NUMBER,
    hier_level      NUMBER DEFAULT 1,
    completename    VARCHAR2(1000),
    building        VARCHAR2(255),
    room            VARCHAR2(255),
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT fk_loc_entity FOREIGN KEY (entities_id) REFERENCES entities(id)
) TABLESPACE TS_MATERIEL;

ALTER TABLE locations ADD CONSTRAINT fk_loc_parent
    FOREIGN KEY (locations_id) REFERENCES locations(id);

CREATE TABLE manufacturers (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(255) NOT NULL UNIQUE,
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP
) TABLESPACE TS_MATERIEL;

CREATE TABLE states (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entities_id     NUMBER,
    name            VARCHAR2(255) NOT NULL,
    is_visible_computer       NUMBER(1) DEFAULT 1,
    is_visible_monitor        NUMBER(1) DEFAULT 1,
    is_visible_printer        NUMBER(1) DEFAULT 1,
    is_visible_phone          NUMBER(1) DEFAULT 1,
    is_visible_peripheral     NUMBER(1) DEFAULT 1,
    is_visible_networkequip   NUMBER(1) DEFAULT 1,
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT fk_states_entity FOREIGN KEY (entities_id) REFERENCES entities(id)
) TABLESPACE TS_MATERIEL;

CREATE TABLE networks (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(255) NOT NULL UNIQUE,
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP
) TABLESPACE TS_MATERIEL;

-- Tables de types et modèles consolidées (résout le problème de redondance GLPI)
CREATE TABLE asset_types (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category        VARCHAR2(50) NOT NULL
        CHECK (category IN ('COMPUTER','MONITOR','PERIPHERAL','PRINTER','PHONE','NETWORK_EQUIPMENT')),
    name            VARCHAR2(255) NOT NULL,
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT uq_asset_type UNIQUE (category, name)
) TABLESPACE TS_MATERIEL;

CREATE TABLE asset_models (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category        VARCHAR2(50) NOT NULL
        CHECK (category IN ('COMPUTER','MONITOR','PERIPHERAL','PRINTER','PHONE','NETWORK_EQUIPMENT')),
    name            VARCHAR2(255) NOT NULL,
    date_creation   TIMESTAMP DEFAULT SYSTIMESTAMP,
    date_mod        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT uq_asset_model UNIQUE (category, name)
) TABLESPACE TS_MATERIEL;

