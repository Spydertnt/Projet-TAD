    CONSTRAINT fk_tu_assigned_by FOREIGN KEY (assigned_by) REFERENCES users(id),
    CONSTRAINT uq_ticket_user UNIQUE (tickets_id, users_id)
) TABLESPACE TS_SUPPORT;

